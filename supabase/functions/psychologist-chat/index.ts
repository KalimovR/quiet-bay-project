serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  // ===== RATE LIMIT CHECK =====
  const clientIP =
    req.headers.get("cf-connecting-ip") ??
    req.headers.get("x-forwarded-for")?.split(",")[0]?.trim() ??
    req.headers.get("x-real-ip") ??
    "unknown";

  const rateLimitResult = checkRateLimit(clientIP);
  if (!rateLimitResult.allowed) {
    return new Response(
      JSON.stringify({
        error: `Слишком много запросов. Подождите ${rateLimitResult.retryAfter} секунд.`,
      }),
      {
        status: 429,
        headers: {
          ...corsHeaders,
          "Content-Type": "application/json",
          "Retry-After": String(rateLimitResult.retryAfter),
        },
      }
    );
  }

  try {
    const { messages, userTier } = await req.json();


    const lastUserMessage =
  messages
    .filter((m: any) => m.role === "user")
    .at(-1)?.content || "";

const detectedState = detectState(lastUserMessage);
const styleRules = detectedState
  ? RESPONSE_STYLE_FILTER[detectedState]
  : null;

    
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    
    if (!LOVABLE_API_KEY) {
      throw new Error("LOVABLE_API_KEY is not configured");
    }

    const subscriptionContext = getSubscriptionContext(userTier || 'free');
    

    console.log("Sending request to Lovable AI with messages:", messages.length, "userTier:", userTier);

    const finalPrompt = `
    ${SYSTEM_PROMPT}
    
    ${subscriptionContext}
    
    ВНУТРЕННИЕ НАСТРОЙКИ (НЕ ОЗВУЧИВАТЬ ПОЛЬЗОВАТЕЛЮ):
    ${styleRules ? JSON.stringify(styleRules) : "Стандартный режим"}
    
    Последнее сообщение пользователя:
    "${lastUserMessage}"
    `;
    
    
    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      
      body: JSON.stringify({
        model: "openai/gpt-5-mini",
        messages: [
          { role: "system", content: finalPrompt },
          ...messages,
        ],
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error("AI gateway error:", response.status, errorText);
      
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Слишком много запросов. Пожалуйста, подождите немного." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Сервис временно недоступен. Попробуйте позже." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      
      return new Response(JSON.stringify({ error: "Ошибка сервиса ИИ" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const data = await response.json();
    console.log("AI response received:", JSON.stringify(data, null, 2));

    const choice0 = data.choices?.[0];
    const rawContent = choice0?.message?.content ?? data.content;

    // Some providers may return content as an array of parts
    let content: string = "";
    if (typeof rawContent === "string") {
      content = rawContent;
    } else if (Array.isArray(rawContent)) {
      content = rawContent
        .map((p: any) => (typeof p?.text === "string" ? p.text : typeof p?.content === "string" ? p.content : ""))
        .join("");
    }

    content = content.trim();

    if (!content) {
      if (choice0?.message?.refusal) {
        content = "Похоже, я не могу ответить на это. Давай переформулируем вопрос или обсудим, что именно тебя тревожит?";
      } else if (choice0?.finish_reason === "length") {
        content = "Похоже, ответ не успел сформулироваться. Давай попробуем ещё раз — что именно пугает тебя в медитации?";
      } else {
        console.error("No content found in response structure:", data);
        throw new Error("No content in AI response");
      }
    }

    return new Response(JSON.stringify({ content }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (error) {
    console.error("psychologist-chat error:", error);
    return new Response(JSON.stringify({ error: error instanceof Error ? error.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
